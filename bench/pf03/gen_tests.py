#!/usr/bin/env python3
"""Write vectors.json as cairo-test tests: one test per (vector, verifier), asserting the
verifier's answer equals the reference verdict. One test per pair gives each its own gas figure.

Usage: python3 -I bench/pf03/gen_tests.py [bench/pf03/vectors.json] [bench/pf03/src/vectors.cairo]
"""

import json
import sys
from pathlib import Path

HERE = Path(__file__).parent
VERIFIERS = [("baseline", "Baseline"), ("compact", "Compact"), ("record", "Record"), ("small", "Small")]


def felts(values: list[str]) -> str:
    return "".join(f"        {v},\n" for v in values)


def main() -> None:
    src = Path(sys.argv[1]) if len(sys.argv) > 1 else HERE / "vectors.json"
    out = Path(sys.argv[2]) if len(sys.argv) > 2 else HERE / "src" / "vectors.cairo"
    vectors = json.loads(src.read_text())["vectors"]
    parts = [
        "//! GENERATED by bench/pf03/gen_tests.py from bench/pf03/vectors.json; do not edit.\n\n"
        "use pqbench_falcon_512::Falcon512ShakeVerifier as Baseline;\n"
        "use pqbench_falcon_512_pf_compact::Falcon512ShakeVerifier as Compact;\n"
        "use pqbench_falcon_512_pf_record::Falcon512ShakeVerifier as Record;\n"
        "use pqbench_falcon_512_pf_small::Falcon512ShakeVerifier as Small;\n"
    ]
    for v in vectors:
        n = v["id"]
        expected = "true" if v["expected"] else "false"
        parts.append(
            f"\n// {n}: {v['category']}, {v['description']} ({v['source']}); reference: {v['reason']}\n"
            f"fn pk_{n}() -> Array<felt252> {{\n    array![\n{felts(v['public_key'])}    ]\n}}\n"
            f"fn sig_{n}() -> Array<felt252> {{\n    array![\n{felts(v['signature'])}    ]\n}}\n"
        )
        for name, impl in VERIFIERS:
            parts.append(
                f"#[test]\nfn v{n}_{name}() {{\n"
                f"    let (pk, sig) = (pk_{n}(), sig_{n}());\n"
                f"    assert_eq!({impl}::verify({v['message']}, pk.span(), sig.span()), {expected});\n}}\n"
            )
        # Input construction alone, subtracted from the gas figures.
        parts.append(
            f"#[test]\nfn v{n}_inputs() {{\n"
            f"    let (pk, sig) = (pk_{n}(), sig_{n}());\n"
            f"    assert!(pk.len() + sig.len() < 1000);\n}}\n"
        )
    out.write_text("".join(parts))


if __name__ == "__main__":
    main()
