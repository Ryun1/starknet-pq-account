#!/usr/bin/env python3
"""Write src/cases.cairo: the PF-04 paired benchmark tests.

Inputs: bench/pf01/corpus.json (Falcon halves), bench/pf04/fixtures.json (ECDSA halves) and
contracts/src/tests_wallets_fixture.cairo (the migration key-possession proof).

Per corpus vector, for each verifier (baseline, compact, record, small, smallkr): `__validate__` of a migrated
account (library call into the verifier class), plus `__validate__` of a directly deployed
`HybridShakeAccount`. On the SELECTED vectors also `__validate_declare__`, `is_valid_signature`,
and a rejected signature (valid ECDSA, Falcon signature of another message: the most expensive
way to fail). Per verifier, one migration: legacy account -> upgrade -> migrate with the proof.

Usage: python3 -I bench/pf04/gen_tests.py
"""

import json
import re
from pathlib import Path

HERE = Path(__file__).resolve().parent
REPO = HERE.parent.parent
VERIFIERS = ("baseline", "compact", "record", "small", "smallkr")
# The first eight-block vector and the most expensive nine-block one (569 words).
SELECTED = (0, 26)


def felts(values: list[str], indent: str = "        ") -> str:
    return "\n".join(f"{indent}{v}," for v in values)


def wallet_fixture() -> dict:
    src = (REPO / "contracts/src/tests_wallets_fixture.cairo").read_text()

    def const(name: str) -> str:
        return re.search(rf"pub const {name}: felt252 =\s*(0x[0-9a-f]+);", src).group(1)

    def array(fn: str) -> list[str]:
        body = re.search(rf"pub fn {fn}\(\) -> Array<felt252> \{{\s*array!\[(.*?)\]", src, re.S).group(1)
        return re.findall(r"0x[0-9a-f]+", body)

    return {"pk": const("ECDSA_PK"), "hash": const("REGISTRATION_HASH"), "r": const("ECDSA_R"),
            "s": const("ECDSA_S"), "falcon_pk": array("falcon_pk"), "falcon_sig": array("falcon_sig")}


def pair(name: str, setup: str, call: str, unused: str = "(account, sig)") -> str:
    return f"""
#[test]
fn setup_{name}() {{
{setup}
    let _ = {unused};
}}

#[test]
fn {name}() {{
{setup}
{call}
}}"""


def main() -> None:
    corpus = json.loads((REPO / "bench/pf01/corpus.json").read_text())["vectors"]
    fixtures = json.loads((HERE / "fixtures.json").read_text())
    ecdsa = {v["id"]: v for v in fixtures["vectors"]}
    wallet = wallet_fixture()
    out = [
        "//! GENERATED by bench/pf04/gen_tests.py; do not edit.",
        "",
        "use pq_hybrid::utils::interface::IHybridAccountDispatcherTrait;",
        "use crate::bench::*;",
        "",
        f"const ECDSA_PK: felt252 = {fixtures['ecdsa_public_key']};",
    ]
    for v in corpus:
        n = v["id"]
        out.append(f"""
// Vector {n}: key {v['key']}, {v['blocks']} blocks, {v['words_used']} words.
const MSG_{n}: felt252 = {v['message']};

fn falcon_pk_{n}() -> Span<felt252> {{
    array![
{felts(v['public_key'])}
    ]
        .span()
}}

fn sig_{n}() -> Array<felt252> {{
    hybrid(
        {ecdsa[n]['ecdsa_r']},
        {ecdsa[n]['ecdsa_s']},
        array![
{felts(v['signature'], '            ')}
        ]
            .span(),
    )
}}""")
        setup = lambda make: f"""    let account = {make};
    let sig = sig_{n}();
    as_transaction(account.contract_address, MSG_{n}, sig.span());"""
        for verifier in VERIFIERS:
            s = setup(f"migratable({verifier.upper()}, ECDSA_PK, falcon_pk_{n}())")
            out.append(pair(f"validate_{verifier}_{n}", s, "    validate(account);"))
            if n in SELECTED:
                out.append(pair(f"declare_{verifier}_{n}", s, "    validate_declare(account);"))
                out.append(pair(f"is_valid_{verifier}_{n}", s,
                                f"    assert_eq!(account.is_valid_signature(MSG_{n}, sig), starknet::VALIDATED);"))
                # Falcon half of vector n over another vector's message, under a valid ECDSA half.
                m = (n + 1) % len(corpus)
                r = f"""    let account = migratable({verifier.upper()}, ECDSA_PK, falcon_pk_{n}());
    let mut sig = array![{ecdsa[m]['ecdsa_r']}, {ecdsa[m]['ecdsa_s']}];
    sig.append_span(sig_{n}().span().slice(2, 60));"""
                out.append(pair(f"reject_{verifier}_{n}", r,
                                f"    assert_eq!(account.is_valid_signature(MSG_{m}, sig), 0);"))
        out.append(pair(f"validate_direct_{n}", setup(f"direct(ECDSA_PK, falcon_pk_{n}())"),
                        "    validate(account);"))

    out.append(f"""
// Migration: contracts/src/tests_wallets_fixture.cairo (key-possession proof over the
// registration hash).
const WALLET_PK: felt252 = {wallet['pk']};

fn wallet_falcon_pk() -> Array<felt252> {{
    array![
{felts(wallet['falcon_pk'])}
    ]
}}

fn wallet_proof() -> Array<felt252> {{
    hybrid(
        {wallet['r']},
        {wallet['s']},
        array![
{felts(wallet['falcon_sig'], '            ')}
        ]
            .span(),
    )
}}""")
    for verifier in VERIFIERS:
        s = f"""    let (account, migratable_class, verifier_class) = legacy({verifier.upper()}, WALLET_PK);
    let falcon_pk = wallet_falcon_pk();
    let proof = wallet_proof();"""
        out.append(pair(f"migrate_{verifier}", s,
                        "    migrate(account, migratable_class, WALLET_PK, falcon_pk, verifier_class, proof);",
                        "(account, migratable_class, verifier_class, falcon_pk, proof)"))
    (HERE / "src/cases.cairo").write_text("\n".join(out) + "\n")


if __name__ == "__main__":
    main()
