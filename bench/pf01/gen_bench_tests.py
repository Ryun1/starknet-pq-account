#!/usr/bin/env python3
"""Write corpus.json as an snforge test file for crates/falcon_512/tests.

Same paired-test method as the upstream bench (crates/falcon_512/tests/bench_shake.cairo):
`baseline_N` builds the inputs of vector N, `verify_N` builds the same inputs and verifies them,
and the verification cost is `verify_N - baseline_N`.

Usage: python3 -I bench/pf01/gen_bench_tests.py CORPUS OUT.cairo
"""

import json
import sys
from pathlib import Path


def felts(values: list[str]) -> str:
    return "\n".join(f"        {v}," for v in values)


def main() -> None:
    corpus = json.loads(Path(sys.argv[1]).read_text())
    out = [
        "//! GENERATED by bench/pf01/gen_bench_tests.py from bench/pf01/corpus.json; do not edit.",
        "",
        "use pqbench_falcon_512::Falcon512ShakeVerifier;",
        "use pqbench_interface::PqSignatureVerifier;",
    ]
    for v in corpus["vectors"]:
        n = v["id"]
        out.append(f"""
// Vector {n}: key {v['key']}, {v['blocks']} blocks, {v['words_used']} words, norm {v['norm']}.
fn pk_{n}() -> Array<felt252> {{
    array![
{felts(v['public_key'])}
    ]
}}

fn sig_{n}() -> Array<felt252> {{
    array![
{felts(v['signature'])}
    ]
}}

#[test]
fn baseline_{n}() {{
    let pk = pk_{n}();
    let sig = sig_{n}();
    assert!(pk.len() == 29 && sig.len() == 60);
}}

#[test]
fn verify_{n}() {{
    let pk = pk_{n}();
    let sig = sig_{n}();
    assert!(Falcon512ShakeVerifier::verify({v['message']}, pk.span(), sig.span()));
}}""")
    Path(sys.argv[2]).write_text("\n".join(out) + "\n")


if __name__ == "__main__":
    main()
