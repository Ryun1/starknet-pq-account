#!/usr/bin/env python3
"""Write src/cases.cairo: the PF-14 paired benchmark tests.

Inputs: the valid vectors of bench/pf14/vectors.json (Falcon-1024 halves; their ECDSA halves are
signed here with the public PF-04 test key), and contracts/src/tests_wallets_fixture.cairo plus
tests_falcon1024_fixture.cairo (the set_pq_key and migration proofs).

Per valid vector: `__validate__` of a HybridMigratableAccountV2 on the Falcon-1024 verifier. On
SELECTED also `__validate_declare__`, `is_valid_signature` and a rejected signature (valid ECDSA,
Falcon-1024 signature of another message). Once each: `set_pq_key` from Falcon-512 to Falcon-1024
on a V2 account, and a legacy account on V2 migrating straight to Falcon-1024.

Usage: python3 -I bench/pf14/gas/gen_tests.py
"""

import json
import re
import sys
from pathlib import Path

HERE = Path(__file__).resolve().parent
REPO = HERE.parent.parent.parent
sys.path.insert(0, str(REPO / "scripts"))
from stark_ecdsa_sign import G, mul, sign  # noqa: E402

# bench/pf04/fixtures.json's key: intentionally public, benchmark fixtures only.
BENCH_KEY = 0x1234567890ABCDEF
# The 16-block vector reading all 1,088 words, and the 17-block one reading the most (1,130).
SELECTED = (5, 7)


def felts(values: list[str], indent: str = "        ") -> str:
    return "\n".join(f"{indent}{v}," for v in values)


def fixture(path: str) -> str:
    return (REPO / "contracts/src" / path).read_text()


def const(src: str, name: str) -> str:
    return re.search(rf"pub const {name}: felt252 =\s*(0x[0-9a-f]+);", src).group(1)


def array(src: str, fn: str) -> list[str]:
    body = re.search(rf"pub fn {fn}\(\) -> Array<felt252> \{{\s*array!\[(.*?)\]", src, re.S).group(1)
    return re.findall(r"0x[0-9a-f]+", body)


def pair(name: str, setup: str, call: str, unused: str = "(account, sig)") -> str:
    return f"""
#[test]
fn setup_{name}() {{
{setup}
    let _ = {unused};
}}

#[test]
fn {name}() {{
{setup}
{call}
}}"""


def main() -> None:
    vectors = [v for v in json.loads((HERE.parent / "vectors.json").read_text())["vectors"]
               if v["category"] == "valid"]
    ids = [v["id"] for v in vectors]
    assert all(n in ids for n in SELECTED)
    ecdsa = {v["id"]: sign(int(v["message"], 16), BENCH_KEY) for v in vectors}
    wallets, f1024 = fixture("tests_wallets_fixture.cairo"), fixture("tests_falcon1024_fixture.cairo")
    out = [
        "//! GENERATED by bench/pf14/gas/gen_tests.py; do not edit.",
        "",
        "use pq_hybrid::migratable_v2::IMigratableV2DispatcherTrait;",
        "use pq_hybrid::utils::interface::IHybridAccountDispatcherTrait;",
        "use crate::bench::*;",
        "",
        f"const ECDSA_PK: felt252 = {hex(mul(BENCH_KEY, G)[0])};",
    ]
    for v in vectors:
        n = v["id"]
        r, s = ecdsa[n]
        out.append(f"""
// Vector {n}: {v['description']} ({v['source']}, key {v['key']}), {v['blocks']} blocks.
const MSG_{n}: felt252 = {v['message']};

fn pk_{n}() -> Span<felt252> {{
    array![
{felts(v['public_key'])}
    ]
        .span()
}}

fn sig_{n}() -> Array<felt252> {{
    hybrid(
        {hex(r)},
        {hex(s)},
        array![
{felts(v['signature'], '            ')}
        ]
            .span(),
    )
}}""")
        setup = f"""    let account = account(falcon1024(), ECDSA_PK, pk_{n}());
    let sig = sig_{n}();
    as_transaction(account.contract_address, MSG_{n}, sig.span());"""
        out.append(pair(f"validate_{n}", setup, "    validate(account);"))
        if n in SELECTED:
            out.append(pair(f"declare_{n}", setup, "    validate_declare(account);"))
            out.append(pair(f"is_valid_{n}", setup,
                            f"    assert_eq!(account.is_valid_signature(MSG_{n}, sig), starknet::VALIDATED);"))
            m = next(w["id"] for w in vectors[ids.index(n):] + vectors if w["message"] != v["message"])
            r2, s2 = ecdsa[m]
            reject = f"""    let account = account(falcon1024(), ECDSA_PK, pk_{n}());
    let mut sig = array![{hex(r2)}, {hex(s2)}];
    sig.append_span(sig_{n}().span().slice(2, 116));"""
            out.append(pair(f"reject_{n}", reject,
                            f"    assert_eq!(account.is_valid_signature(MSG_{m}, sig), 0);"))

    out.append(f"""
// Scheme switch: tests_wallets_fixture.cairo's keys (ECDSA_PK, Falcon-512 key A) and
// tests_falcon1024_fixture.cairo's Falcon-1024 key and proofs.
const WALLET_PK: felt252 = {const(wallets, 'ECDSA_PK')};

fn falcon512_pk() -> Span<felt252> {{
    array![
{felts(array(wallets, 'falcon_pk'))}
    ]
        .span()
}}

fn falcon1024_pk() -> Array<felt252> {{
    array![
{felts(array(f1024, 'falcon1024_pk'))}
    ]
}}

fn rotation_proof() -> Array<felt252> {{
    array![
{felts(array(f1024, 'falcon1024_rotation_proof'))}
    ]
}}

fn registration_proof() -> Array<felt252> {{
    array![
{felts(array(f1024, 'falcon1024_registration_proof'))}
    ]
}}""")
    s = """    let account = account(falcon512(), WALLET_PK, falcon512_pk()).contract_address;
    let (key, verifier, proof) = (falcon1024_pk(), falcon1024(), rotation_proof());"""
    out.append(pair("set_pq_key", s, "    as_self(account).set_pq_key(key, verifier, 0.try_into().unwrap(), proof);",
                    "(account, key, verifier, proof)"))
    s = """    let account = legacy_on_v2(WALLET_PK);
    let (key, verifier, proof) = (falcon1024_pk(), falcon1024(), registration_proof());"""
    out.append(pair("migrate", s,
                    "    as_self(account).migrate(WALLET_PK, key, verifier, 0.try_into().unwrap(), proof);",
                    "(account, key, verifier, proof)"))
    (HERE / "src/cases.cairo").write_text("\n".join(out) + "\n")


if __name__ == "__main__":
    main()
