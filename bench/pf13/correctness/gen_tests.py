#!/usr/bin/env python3
"""Write vectors.json as cairo-test tests, bench/pf14/gen_tests.py's scheme with three paths:

  baseline   the lane baseline's MlDsa44Verifier::verify, from scratch;
  record     the pinned record's MlDsa44Verifier::verify, from scratch;
  cached     the pinned record through cache::precompute + cache::verify_cached, as the account
             runs it (a key precompute refuses is a rejection: MlDsa44KeySetup panics on it).

Per vector also `inputs` (inputs only) and `precompute` (inputs + precompute), which summarize.py
subtracts. Plus the cache's own tests (src/cache_tests.cairo, a cache that is not the key's) and
the baseline crate's NIST ACVP sigVer tests, copied to src/acvp.cairo: those use the byte-level
`verify_internal` / `verify_mu`, which only the baseline has.

Usage: python3 -I bench/pf13/correctness/gen_tests.py
"""

import json
from pathlib import Path

HERE = Path(__file__).resolve().parent
REPO = HERE.parent.parent.parent
ACVP = REPO / "vendor/cairo-pq-verifiers/crates/ml_dsa_44/tests/acvp.cairo"
HEADER = "//! GENERATED by bench/pf13/correctness/gen_tests.py; do not edit.\n\n"


def felts(values: list[str]) -> str:
    return "".join(f"        {v},\n" for v in values)


def array_fn(name: str, values: list[str]) -> str:
    return f"fn {name}() -> Array<felt252> {{\n    array![\n{felts(values)}    ]\n}}\n"


def vector_tests(vectors) -> str:
    parts = [HEADER,
             "use pqbench_ml_dsa_44::MlDsa44Verifier as Baseline;\n"
             "use pqbench_ml_dsa_44_pf_record::MlDsa44Verifier as Record;\n"
             "use pqbench_ml_dsa_44_pf_record::verx::cache::{precompute, verify_cached};\n"]
    for v in vectors:
        n, m, expected = v["id"], v["message"], "true" if v["expected"] else "false"
        parts.append(
            f"\n// {n}: {v['category']}, {v['description']} ({v['source']}); reference: {v['reason']}\n"
            + array_fn(f"pk_{n}", v["public_key"]) + array_fn(f"sig_{n}", v["signature"]))
        for name, impl in (("baseline", "Baseline"), ("record", "Record")):
            parts.append(
                f"#[test]\nfn v{n}_{name}() {{\n    let (pk, sig) = (pk_{n}(), sig_{n}());\n"
                f"    assert_eq!({impl}::verify({m}, pk.span(), sig.span()), {expected});\n}}\n")
        parts.append(
            f"#[test]\nfn v{n}_cached() {{\n    let (pk, sig) = (pk_{n}(), sig_{n}());\n"
            f"    let got = match precompute(pk.span()) {{\n"
            f"        Some((tr, a)) => verify_cached({m}, pk.span(), sig.span(), tr.span(), a.span()),\n"
            f"        None => false,\n    }};\n    assert_eq!(got, {expected});\n}}\n"
            f"#[test]\nfn v{n}_precompute() {{\n    let (pk, sig) = (pk_{n}(), sig_{n}());\n"
            f"    let cache = precompute(pk.span());\n    assert!(sig.len() < 1000 && (cache.is_some() || true));\n}}\n"
            f"#[test]\nfn v{n}_inputs() {{\n    let (pk, sig) = (pk_{n}(), sig_{n}());\n"
            f"    assert!(pk.len() + sig.len() < 1000);\n}}\n")
    return "".join(parts)


def cache_tests(vectors) -> str:
    """A valid noble signature of key A checked against caches that are not exactly key A's."""
    noble = [v for v in vectors if v["source"] == "noble" and v["category"] == "valid"]
    a = noble[0]
    b = next(v for v in noble if v["key"] != a["key"])
    m = a["message"]
    cases = {
        "own_cache_accepts": ("tr_of(pk_a())", "a_of(pk_a())", "true"),
        "other_keys_cache_rejects": ("tr_of(pk_b())", "a_of(pk_b())", "false"),
        "other_keys_tr_rejects": ("tr_of(pk_b())", "a_of(pk_a())", "false"),
        "other_keys_a_hat_rejects": ("tr_of(pk_a())", "a_of(pk_b())", "false"),
        "tampered_tr_first_slot_rejects": ("set(tr_of(pk_a()), 0, 1)", "a_of(pk_a())", "false"),
        "tampered_tr_last_slot_rejects": ("set(tr_of(pk_a()), 7, 1)", "a_of(pk_a())", "false"),
        "tampered_a_hat_first_slot_rejects": ("tr_of(pk_a())", "set(a_of(pk_a()), 0, 1)", "false"),
        "tampered_a_hat_middle_slot_rejects": ("tr_of(pk_a())", "set(a_of(pk_a()), 205, 1)", "false"),
        "tampered_a_hat_last_slot_rejects": ("tr_of(pk_a())", "set(a_of(pk_a()), 409, 1)", "false"),
        "short_a_hat_rejects": ("tr_of(pk_a())", "set(a_of(pk_a()), 410, 0)", "false"),
    }
    parts = [HEADER,
             f"//! The cache: key A = {a['key']}, signature = vector {a['id']}; key B = {b['key']}.\n"
             "//! Not reference verdicts: a tr or A-hat that is not key A's is a different equation.\n\n"
             "use pqbench_ml_dsa_44_pf_record::verx::cache::{precompute, verify_cached};\n\n"
             + array_fn("pk_a", a["public_key"]) + array_fn("pk_b", b["public_key"])
             + array_fn("sig_a", a["signature"])
             + "\n/// `felts` with `delta` added to slot `i`; i == len drops the last slot instead.\n"
             "fn set(felts: Array<felt252>, i: u32, delta: felt252) -> Array<felt252> {\n"
             "    let mut out = array![];\n    let n = felts.len();\n"
             "    for (j, f) in felts.into_iter().enumerate() {\n"
             "        if i == n && j == n - 1 {\n            break;\n        }\n"
             "        out.append(if j == i { f + delta } else { f });\n    }\n    out\n}\n"
             "fn tr_of(pk: Array<felt252>) -> Array<felt252> {\n"
             "    let (tr, _) = precompute(pk.span()).unwrap();\n    tr\n}\n"
             "fn a_of(pk: Array<felt252>) -> Array<felt252> {\n"
             "    let (_, a) = precompute(pk.span()).unwrap();\n    a\n}\n"]
    for name, (tr, ah, expected) in cases.items():
        parts.append(
            f"\n#[test]\nfn {name}() {{\n"
            f"    let (pk, sig, tr, ah) = (pk_a(), sig_a(), {tr}, {ah});\n"
            f"    assert_eq!(verify_cached({m}, pk.span(), sig.span(), tr.span(), ah.span()), {expected});\n}}\n")
    return "".join(parts)


def main() -> None:
    vectors = json.loads((HERE / "vectors.json").read_text())["vectors"]
    src = HERE / "src"
    (src / "vectors.cairo").write_text(vector_tests(vectors))
    (src / "cache_tests.cairo").write_text(cache_tests(vectors))
    (src / "acvp.cairo").write_text(HEADER.replace("; do not edit", f" from {ACVP.relative_to(REPO)}; do not edit")
                                    + ACVP.read_text())


if __name__ == "__main__":
    main()
