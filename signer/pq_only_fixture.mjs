// Writes the cairo-test fixture for PQ-only mode (ARCH-01): a Falcon-only proof by Falcon key A
// over rotation_hash(ECDSA_PK, falcon_pk()), what set_pq_key checks when an account moves to a
// Falcon-only verifier and keeps its key. Same throwaway keys as rotation_fixture.mjs. Every
// other signature tests_pq_only.cairo needs is the Falcon half of an existing fixture.
import { ec, num } from "starknet";
import { readFileSync, writeFileSync } from "node:fs";
import { falcon512, makeNtt, publicKeyFelts } from "./falcon_adapter.mjs";
import { falconSignature, rotationHash } from "./pq_account_kit.mjs";
import { ROOTS } from "./config.mjs";

const OUT = new URL("../contracts/src/tests_pq_only_fixture.cairo", import.meta.url);
const ntt = makeNtt(JSON.parse(readFileSync(ROOTS, "utf8")));
const { publicKey, secretKey } = falcon512.keygen(new Uint8Array(48).fill(7)); // falcon_pk()
const keys = { falconPublicKey: publicKey, falconSecretKey: secretKey, falconFelts: publicKeyFelts(publicKey, ntt).map(num.toHex) };
const ecdsaPublicKey = num.toHex(ec.starkCurve.getStarkKey("0x5eed03")); // ECDSA_PK
const message = rotationHash(ecdsaPublicKey, keys.falconFelts);

writeFileSync(OUT, `//! Fixture for PQ-only mode (ARCH-01), generated by signer/pq_only_fixture.mjs.
//! Throwaway keys: ECDSA_PK and falcon_pk() of tests_wallets_fixture.cairo.

/// rotation_hash(ECDSA_PK, falcon_pk()): what set_pq_key's proof signs when the key stays.
pub const PQ_ONLY_ROTATION_HASH: felt252 = ${message};

/// Falcon-512 alone (60 felts, no ECDSA) by falcon_pk() over PQ_ONLY_ROTATION_HASH.
pub fn pq_only_proof() -> Array<felt252> {
    array![
${falconSignature(message, keys).map((x) => `        ${x},`).join("\n")}
    ]
}
`);
console.log("fixture written:", OUT.pathname);
