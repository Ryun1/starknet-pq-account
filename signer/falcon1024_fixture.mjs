// Writes the cairo-test fixture for the Falcon-1024 scheme switch (PF-14): a throwaway
// Falcon-1024 key and hybrid signatures by ECDSA_PK and that key, built by the kit and
// signer/falcon_adapter.mjs at n = 1024. Same ECDSA key as tests_wallets_fixture.cairo.
import { ec, num } from "starknet";
import { readFileSync, writeFileSync } from "node:fs";
import { falcon1024, makeNtt, publicKeyFelts } from "./falcon_adapter.mjs";
import { hybridSignature, registrationHash, rotationHash } from "./pq_account_kit.mjs";
import { WALLETS_FIXTURE } from "./config.mjs";

const OUT = new URL("../contracts/src/tests_falcon1024_fixture.cairo", import.meta.url);
const ntt = makeNtt(JSON.parse(readFileSync(new URL("./falcon1024_ntt_roots.json", import.meta.url), "utf8")));
const wallets = readFileSync(WALLETS_FIXTURE, "utf8");
const constant = (name) => wallets.match(new RegExp(`pub const ${name}: felt252 =\\s*(0x[0-9a-f]+);`))[1];

const ecdsaPrivateKey = "0x5eed03"; // tests_wallets_fixture.cairo's ECDSA_PK
const ecdsaPublicKey = num.toHex(ec.starkCurve.getStarkKey(ecdsaPrivateKey));
if (BigInt(ecdsaPublicKey) !== BigInt(constant("ECDSA_PK"))) throw new Error("ECDSA key differs from tests_wallets_fixture.cairo");
const { publicKey, secretKey } = falcon1024.keygen(new Uint8Array(48).fill(9));
const keys = { ecdsaPrivateKey, ecdsaPublicKey, falconPublicKey: publicKey, falconSecretKey: secretKey,
  falconFelts: publicKeyFelts(publicKey, ntt).map(num.toHex) };

const MSG = constant("REGISTRATION_HASH"); // the transaction hash tests_scheme.cairo uses
const rotation = rotationHash(ecdsaPublicKey, keys.falconFelts);
const registration = registrationHash(ecdsaPublicKey, keys.falconFelts);

const arr = (xs) => xs.map((x) => `        ${num.toHex(x)},`).join("\n");
const fn = (name, xs, doc) => `/// ${doc}\npub fn ${name}() -> Array<felt252> {\n    array![\n${arr(xs)}\n    ]\n}\n`;
writeFileSync(OUT, `//! Fixture for the Falcon-1024 scheme switch, generated by signer/falcon1024_fixture.mjs.
//! Throwaway keys: ECDSA_PK of tests_wallets_fixture.cairo and a Falcon-1024 key from a fixed
//! seed. Each signature is a hybrid signature [r, s, Falcon-1024 x116] by those two keys.

/// rotation_hash(ECDSA_PK, falcon1024_pk()): what set_pq_key's proof signs.
pub const F1024_ROTATION_HASH: felt252 = ${rotation};
/// registration_hash(ECDSA_PK, falcon1024_pk()): what a migration's proof signs.
pub const F1024_REGISTRATION_HASH: felt252 = ${registration};

${fn("falcon1024_pk", keys.falconFelts, "The Falcon-1024 public key, 57 felts.")}
${fn("falcon1024_rotation_proof", hybridSignature(rotation, keys), "Signs F1024_ROTATION_HASH.")}
${fn("falcon1024_registration_proof", hybridSignature(registration, keys), "Signs F1024_REGISTRATION_HASH.")}
${fn("falcon1024_sig", hybridSignature(MSG, keys), "Signs REGISTRATION_HASH, the transaction hash of tests_scheme.cairo.")}`);
console.log("fixture written:", OUT.pathname);
