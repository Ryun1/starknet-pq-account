// Writes the cairo-test fixture for ML-DSA-44 (PF-13): a throwaway ML-DSA-44 key and hybrid
// signatures [r, s, ML-DSA-44 x79] by ECDSA_PK (tests_wallets_fixture.cairo) and that key.
import { ec, num } from "starknet";
import { readFileSync, writeFileSync } from "node:fs";
import { ml_dsa44, publicKeyFelts, signatureFelts, signTxHash } from "./mldsa_adapter.mjs";
import { registrationHash, rotationHash } from "./pq_account_kit.mjs";
import { WALLETS_FIXTURE } from "./config.mjs";

const OUT = new URL("../contracts/src/tests_mldsa_fixture.cairo", import.meta.url);
const wallets = readFileSync(WALLETS_FIXTURE, "utf8");
const constant = (name) => wallets.match(new RegExp(`pub const ${name}: felt252 =\\s*(0x[0-9a-f]+);`))[1];

const ecdsaPrivateKey = "0x5eed03"; // tests_wallets_fixture.cairo's ECDSA_PK
const ecdsaPublicKey = num.toHex(ec.starkCurve.getStarkKey(ecdsaPrivateKey));
if (BigInt(ecdsaPublicKey) !== BigInt(constant("ECDSA_PK"))) throw new Error("ECDSA key differs from tests_wallets_fixture.cairo");
const { publicKey, secretKey } = ml_dsa44.keygen(new Uint8Array(32).fill(13));
const pkFelts = publicKeyFelts(publicKey).map(num.toHex);
const sign = (h) => {
  const e = ec.starkCurve.sign(num.toHex(h), ecdsaPrivateKey);
  return [e.r, e.s, ...signatureFelts(signTxHash(BigInt(h), secretKey))];
};

const MSG = constant("REGISTRATION_HASH"); // the transaction hash tests_scheme.cairo uses
const rotation = rotationHash(ecdsaPublicKey, pkFelts);
const registration = registrationHash(ecdsaPublicKey, pkFelts);
// Key B, for a rotation within ML-DSA-44 (the cache must follow the key).
const b = ml_dsa44.keygen(new Uint8Array(32).fill(14));
const pkFeltsB = publicKeyFelts(b.publicKey).map(num.toHex);
const rotationB = rotationHash(ecdsaPublicKey, pkFeltsB);
const signB = (h) => {
  const e = ec.starkCurve.sign(num.toHex(h), ecdsaPrivateKey);
  return [e.r, e.s, ...signatureFelts(signTxHash(BigInt(h), b.secretKey))];
};

const arr = (xs) => xs.map((x) => `        ${num.toHex(x)},`).join("\n");
const fn = (name, xs, doc) => `/// ${doc}\npub fn ${name}() -> Array<felt252> {\n    array![\n${arr(xs)}\n    ]\n}\n`;
writeFileSync(OUT, `//! Fixture for ML-DSA-44 (PF-13), generated by signer/mldsa_fixture.mjs. Throwaway keys:
//! ECDSA_PK of tests_wallets_fixture.cairo and an ML-DSA-44 key from a fixed seed. Each signature is
//! a hybrid signature [r, s, ML-DSA-44 x79] by those two keys.

/// rotation_hash(ECDSA_PK, mldsa_pk()): what set_pq_key's proof signs.
pub const MLDSA_ROTATION_HASH: felt252 = ${rotation};
/// registration_hash(ECDSA_PK, mldsa_pk()): what a migration's proof signs.
pub const MLDSA_REGISTRATION_HASH: felt252 = ${registration};

${fn("mldsa_pk", pkFelts, "The ML-DSA-44 public key, 43 felts.")}
${fn("mldsa_pk_b", pkFeltsB, "ML-DSA-44 key B (seed 14).")}
${fn("mldsa_rotation_proof_b", signB(rotationB), "Signs rotation_hash(ECDSA_PK, mldsa_pk_b()).")}
${fn("mldsa_sig_b", signB(MSG), "Signs REGISTRATION_HASH with key B.")}
${fn("mldsa_rotation_proof", sign(rotation), "Signs MLDSA_ROTATION_HASH.")}
${fn("mldsa_registration_proof", sign(registration), "Signs MLDSA_REGISTRATION_HASH.")}
${fn("mldsa_sig", sign(MSG), "Signs REGISTRATION_HASH, the transaction hash of tests_scheme.cairo.")}`);
console.log("fixture written:", OUT.pathname);
